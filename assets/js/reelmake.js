(function(){
  var ORDER=["ja","en","pt-BR","zh","ko","de","es","fr","hi","ar","ru","tr","vi","th","it"];
  var D=window.REELMAKE_I18N;
  function pick(){
    var n=((navigator.languages&&navigator.languages[0])||navigator.language||"ja").toLowerCase();
    for(var i=0;i<ORDER.length;i++){var c=ORDER[i].toLowerCase();if(n===c)return ORDER[i];}
    var base=n.split("-")[0];
    var map={pt:"pt-BR",zh:"zh"};
    for(var j=0;j<ORDER.length;j++){if(ORDER[j].toLowerCase().split("-")[0]===base)return ORDER[j];}
    if(map[base])return map[base];
    return "ja";
  }
  function set(attr,val){
    var els=document.querySelectorAll("[data-rm-"+attr+"]");
    for(var i=0;i<els.length;i++)els[i].textContent=val;
  }
  function apply(code){
    var d=D[code];if(!d)return;
    set("title",d.title);set("subtitle",d.subtitle);set("promo",d.promo);
    var shot=document.querySelector("[data-rm-shot]");
    if(shot&&d.shot){shot.src=d.shot;shot.alt=d.title;}
    var sec=document.getElementById("reel-make");
    if(sec)sec.setAttribute("dir",d.dir||"ltr");
    var sel=document.getElementById("rm-lang");if(sel)sel.value=code;
    try{localStorage.setItem("rmLang",code);}catch(e){}
  }
  document.addEventListener("DOMContentLoaded",function(){
    var sel=document.getElementById("rm-lang");
    if(sel){
      sel.innerHTML=ORDER.map(function(c){return '<option value="'+c+'">'+D[c].label+'</option>';}).join("");
      sel.addEventListener("change",function(e){apply(e.target.value);});
    }
    var saved=null;try{saved=localStorage.getItem("rmLang");}catch(e){}
    apply(saved&&D[saved]?saved:pick());
  });
})();
